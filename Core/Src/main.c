void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	if(huart-> Instance==USART3) {
		bufferLora[contadorLoraBuffer] = loraDataIn;
		contadorLoraBuffer ++;

		if(contadorLoraBuffer >= TAMANHO_BUFFER_LORA) {
			apagaLoRaBuffer();
		}

		//HAL_UART_Transmit(&huart4, &loraDataIn, 1, 100); //Debug

		if(loraDataIn == 0x0A) {
			flagPacoteLora = true;
		}
	}

	if(huart-> Instance==USART4) { //RS485
		if(rs485DataIn == 0x00) {
			return;
		}
		bufferRS485[contadorRS485Buffer] = rs485DataIn;
		contadorRS485Buffer ++;

		if(contadorRS485Buffer >= TAMANHO_BUFFER_RS485) {
			apagaRS485Buffer();
		}

		if(rs485DataIn == 0x0A) {
			flagPacoteRS485 = true;
		}
	}
}

